"""Moving rules up and down on a firewall, on probation (like a rule deployment, but for the ORDER).

OPNsense evaluates rules top to bottom and the first match wins, so a rule's position is part of its meaning. A move is
therefore never "just done": the new order is live but unconfirmed for ``deploy_confirm_window_seconds``; without a
confirmation the sweeper puts the rule back where it was (and a person can do that at once, too).

How a move is made (all checked live on OPNsense 26.7, see opnsense_client.py): ``moveRuleBefore(rule, target)`` puts a
rule directly in front of another one of the same priority group; "to the end" has no call of its own and is made
by giving the rule a ``sequence`` above every other rule of its group (setRule with ONLY that field leaves everything
else alone). Rules that are not in the model (legacy), automatic ones and rules of another group cannot be moved or
used as a target. Every move records where the rule was (the neighbours before and after it) BEFORE the firewall is
touched; moves on one firewall that are still open are undone newest first.

A rule managed by the policy hierarchy is not movable here: the hierarchy decides its place and puts it back.
"""
from datetime import datetime, timedelta, timezone

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app import runtime_settings
from app.errors import ErrorCode, api_error
from app.models.host import OpnsenseHost
from app.models.policy_hierarchy_rule_deployment import PolicyHierarchyRuleDeployment
from app.models.rule_order import OPEN_STATUSES, RuleOrderChange
from app.services import opnsense_client
from app.services.opnsense_client import OpnsenseAPIError

MAX_SEQUENCE = 999999


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _truthy(value) -> bool:
    return str(value).strip().lower() in ("1", "true", "yes", "on")


def group_of(row: dict) -> str:
    return str(row.get("prio_group") or str(row.get("sort_order") or "").partition(".")[0])


def order_of(row: dict) -> float:
    try:
        return float(row.get("sort_order"))
    except (TypeError, ValueError):
        return float("inf")


def is_model_rule(row: dict) -> bool:
    """A rule moveRuleBefore can work with: in the MVC model (not legacy), not generated by the system."""
    return bool(row.get("uuid")) and not _truthy(row.get("legacy")) and not _truthy(row.get("is_automatic"))


def members(rows: list[dict], group: str) -> list[dict]:
    """The movable rules of one priority group in firewall order."""
    return sorted((r for r in rows if group_of(r) == group and is_model_rule(r)), key=order_of)


async def live_rows(host: OpnsenseHost) -> list[dict]:
    data = await opnsense_client.search_rules(host, all_rows=True)
    return [r for r in (data.get("rows") if isinstance(data, dict) else None) or [] if isinstance(r, dict) and r.get("uuid")]


def _next_sequence(group_members: list[dict]) -> int:
    seqs = []
    for r in group_members:
        try:
            seqs.append(int(str(r.get("sequence"))))
        except (TypeError, ValueError):
            pass
    return min((max(seqs) if seqs else 0) + 100, MAX_SEQUENCE)


def is_directly_before(ids: list[str], rule: str, target: str | None) -> bool:
    """ids = group order. target None: the rule is the last one."""
    if rule not in ids:
        return False
    i = ids.index(rule)
    return (i == len(ids) - 1) if target is None else (i + 1 < len(ids) and ids[i + 1] == target)


async def _place(host: OpnsenseHost, rule_uuid: str, target: str | None, group: str) -> None:
    """Put the rule directly before ``target`` (None = end of its group), apply, and read the order back."""
    rows = await live_rows(host)
    group_members = members(rows, group)
    ids = [r["uuid"] for r in group_members]
    if rule_uuid not in ids or (target is not None and target not in ids):
        raise OpnsenseAPIError("Regel oder Ziel nicht mehr auf der Firewall")
    if not is_directly_before(ids, rule_uuid, target):
        if target is not None:
            await opnsense_client.move_rule_before(host, rule_uuid, target)
        else:
            await opnsense_client.set_rule(host, rule_uuid, {"sequence": str(_next_sequence([r for r in group_members if r["uuid"] != rule_uuid]))})
    await opnsense_client.apply(host)
    after = [r["uuid"] for r in members(await live_rows(host), group)]
    if not is_directly_before(after, rule_uuid, target):
        raise OpnsenseAPIError("Die Reihenfolge auf der Firewall entspricht nicht der angeforderten")


def _window() -> timedelta:
    return timedelta(seconds=runtime_settings.value("deploy_confirm_window_seconds"))


async def open_changes(db: AsyncSession, host_ids) -> list[RuleOrderChange]:
    ids = list(host_ids)
    if not ids:
        return []
    return list((await db.scalars(select(RuleOrderChange).where(
        RuleOrderChange.host_id.in_(ids), RuleOrderChange.status.in_(OPEN_STATUSES)).order_by(RuleOrderChange.created_at))).all())


async def has_open_change(db: AsyncSession, host_ids) -> bool:
    ids = list(host_ids)
    return bool(ids and await db.scalar(select(RuleOrderChange.id).where(
        RuleOrderChange.host_id.in_(ids), RuleOrderChange.status.in_(OPEN_STATUSES)).limit(1)))


async def hierarchy_uuids(db: AsyncSession, host: OpnsenseHost) -> set[str]:
    return set((await db.scalars(select(PolicyHierarchyRuleDeployment.opnsense_policy_hierarchy_uuid).where(
        PolicyHierarchyRuleDeployment.host_id == host.id,
        PolicyHierarchyRuleDeployment.opnsense_policy_hierarchy_uuid.is_not(None)))).all())


async def move_rule(db: AsyncSession, host: OpnsenseHost, *, actor: str, rule_uuid: str, before_uuid: str | None) -> RuleOrderChange | None:
    """Move ``rule_uuid`` directly before ``before_uuid`` (None = to the end of its group). Returns None if it already
    is there. The change is live afterwards, pending confirmation."""
    from app.services.host_maintenance_service import ensure_no_maintenance, ensure_no_open_cleanup
    from app.services.policy_service import policy_lock
    await policy_lock(db)
    # Other open MOVES are fine (a series is confirmed together); a failed revert or anything else running is not.
    await ensure_no_maintenance(db, [host], cleanup=False)
    await ensure_no_open_cleanup(db, [host])
    if any(c.status == "revert_failed" for c in await open_changes(db, [host.id])):
        raise api_error(409, ErrorCode.OPEN_ORDER_CHANGE_BLOCKS_DEPLOY)
    try:
        rows = await live_rows(host)
    except OpnsenseAPIError as exc:
        raise api_error(502, ErrorCode.ORDER_HOST_UNREACHABLE, host=host.name, reason=str(exc)[:200]) from exc
    own = next((r for r in rows if r["uuid"] == rule_uuid), None)
    if own is None:
        raise api_error(404, ErrorCode.ORDER_RULE_NOT_FOUND)
    managed_by_hierarchy = await hierarchy_uuids(db, host)
    if not is_model_rule(own) or rule_uuid in managed_by_hierarchy:
        raise api_error(409, ErrorCode.ORDER_RULE_NOT_MOVABLE)
    group = group_of(own)
    ids = [r["uuid"] for r in members(rows, group)]
    if before_uuid is not None and (before_uuid not in ids or before_uuid == rule_uuid or before_uuid in managed_by_hierarchy):
        raise api_error(409, ErrorCode.ORDER_RULE_NOT_MOVABLE)
    if is_directly_before(ids, rule_uuid, before_uuid):
        return None
    i = ids.index(rule_uuid)
    change = RuleOrderChange(
        host_id=host.id, rule_uuid=rule_uuid, description=str(own.get("description") or "")[:255], prio_group=group,
        anchor_next=ids[i + 1] if i + 1 < len(ids) else None, anchor_prev=ids[i - 1] if i > 0 else None,
        target_uuid=before_uuid, status="pending", actor=actor[:150], revert_deadline=_now() + _window())
    db.add(change)
    await db.flush()
    await db.commit()  # intent first: from here on a crash leaves a pending change the sweeper takes back
    await policy_lock(db)
    try:
        await _place(host, rule_uuid, before_uuid, group)
    except OpnsenseAPIError as exc:
        # Refused or not visible afterwards: undo at once; if that fails too the row stays pending and armed.
        undone = await _restore(db, host, change)
        change.message = f"Verschieben fehlgeschlagen: {str(exc)[:300]}"
        if undone:
            change.status, change.revert_deadline, change.finished_at = "failed", None, _now()
        await db.commit()
        raise api_error(502, ErrorCode.ORDER_MOVE_FAILED, host=host.name, reason=str(exc)[:200]) from exc
    # Every open move of this host gets a fresh window: the whole series is confirmed or taken back together.
    deadline = _now() + _window()
    for open_change in await open_changes(db, [host.id]):
        if open_change.status == "pending":
            open_change.revert_deadline = deadline
    await db.commit()
    return change


async def _restore(db: AsyncSession, host: OpnsenseHost, change: RuleOrderChange) -> bool:
    """Put the rule back where it was. True = it is there (or gone), False = could not (or no longer possible)."""
    try:
        rows = await live_rows(host)
        group_members = members(rows, change.prio_group)
        ids = [r["uuid"] for r in group_members]
        if change.rule_uuid not in ids:
            return True  # deleted meanwhile: nothing to put back
        without = [i for i in ids if i != change.rule_uuid]
        if change.anchor_next is None:
            target = None
        elif change.anchor_next in without:
            target = change.anchor_next
        elif change.anchor_prev in without:
            k = without.index(change.anchor_prev)
            target = without[k + 1] if k + 1 < len(without) else None
        else:
            change.message = "Alte Position nicht wiederherstellbar: die Nachbarregeln gibt es nicht mehr."
            return False
        await _place(host, change.rule_uuid, target, change.prio_group)
        return True
    except OpnsenseAPIError as exc:
        change.message = f"Zurücksetzen fehlgeschlagen: {str(exc)[:300]}"
        return False


async def revert_host(db: AsyncSession, host: OpnsenseHost) -> list[RuleOrderChange]:
    """Take every open move of the host back, newest first. Returns the changes that were handled."""
    from app.services.policy_service import policy_lock
    await policy_lock(db)
    handled = []
    for change in reversed(await open_changes(db, [host.id])):
        if await _restore(db, host, change):
            change.status, change.revert_deadline, change.finished_at = "reverted", None, _now()
            change.message = None
        else:
            change.status, change.revert_deadline = "revert_failed", None
        handled.append(change)
        await db.flush()
        if change.status == "revert_failed":
            break  # older moves depend on this one having been undone: stop, a person has to look
    await db.commit()
    return handled


async def confirm_host(db: AsyncSession, host: OpnsenseHost) -> list[RuleOrderChange]:
    """"I still have access": make the pending moves of the host permanent."""
    from app.services.policy_service import policy_lock
    await policy_lock(db)
    pending = [c for c in await open_changes(db, [host.id]) if c.status == "pending" and c.revert_deadline and c.revert_deadline > _now()]
    if not pending:
        raise api_error(404, ErrorCode.ORDER_NOTHING_OPEN)
    for change in pending:
        change.status, change.revert_deadline, change.finished_at, change.message = "confirmed", None, _now(), None
    await db.commit()
    return pending


async def sweep_expired_order_changes(db: AsyncSession) -> list[RuleOrderChange]:
    """Take back every host's moves whose confirmation window passed (called from the sweeper loop in main.py)."""
    from app.services.policy_service import policy_lock
    await policy_lock(db)
    host_ids = set((await db.scalars(select(RuleOrderChange.host_id).where(
        RuleOrderChange.status == "pending", RuleOrderChange.revert_deadline <= _now()))).all())
    touched = []
    for host_id in host_ids:
        host = await db.get(OpnsenseHost, host_id)
        if host is not None:
            touched.extend(await revert_host(db, host))
    return touched
